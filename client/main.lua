-- Client-side script for the sleep emote resource

local QBCore = exports['qb-core']:GetCoreObject()

-- Function to start the sleep emote
local function startSleepEmote()
    TriggerEvent('animations:client:EmoteCommandStart', {"sleep"})
    TriggerEvent('qb-inventory:client:disableInventory')
    TriggerEvent('qb-weapons:client:disableWeapons')
    TriggerEvent('qb-police:client:disablePunch')
    TriggerEvent('qb-police:client:disableShoot')
    TriggerEvent('qb-police:client:disableInventory')
    TriggerEvent('qb-police:client:disableEmoteCancel')
    TriggerEvent('qb-police:client:disableMovement')
    TriggerEvent('qb-police:client:disableScreenEffects')
    TriggerEvent('qb-police:client:disableScreenDarkness')
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
    TriggerEvent('qb-police:client:disableScreenDarkness', true)
    TriggerEvent('qb-police:client:disableScreenDarkness', false)
end

-- Function to stop the sleep emote
local function stopSleepEmote()
    TriggerEvent('animations:client:EmoteCommandStart', {"c"})
    TriggerEvent('qb-inventory:client:enableInventory')
    TriggerEvent('qb-weapons:client:enableWeapons')
    TriggerEvent('qb-police:client:enablePunch')
    TriggerEvent('qb-police:client:enableShoot')
    TriggerEvent('qb-police:client:enableInventory')
    TriggerEvent('qb-police:client:enableEmoteCancel')
    TriggerEvent('qb-police:client:enableMovement')
    TriggerEvent('qb-police:client:enableScreenEffects')
    TriggerEvent('qb-police:client:enableScreenDarkness')
end

-- Register the command to start the sleep emote
RegisterCommand('sleep', function()
    startSleepEmote()
    Citizen.SetTimeout(300000, function()
        stopSleepEmote()
    end)
end, false)